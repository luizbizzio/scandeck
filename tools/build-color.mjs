import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { deflateRawSync } from 'node:zlib';
import { jabcode } from 'etiket';
import { base43Encode, packScript } from '../protocol.js';
const root=new URL('../',import.meta.url);
const file=path=>new URL(path,root);
mkdirSync(file('assets/'),{recursive:true});

// The JAB Code encoder in etiket is experimental. ZXing does not read JAB.
const html=readFileSync(file('examples/colorpath-jab.html'),'utf8').trim();
const jabPayload='SD1:'+base43Encode(deflateRawSync(Buffer.from(html)));
const jabImage=jabcode(jabPayload,{colors:8});
if(typeof jabImage!=='string'||!jabImage.includes('<svg'))throw Error('JAB Code generator did not return SVG');
writeFileSync(file('assets/colorpath-jab.svg'),jabImage);
writeFileSync(file('assets/colorpath-jab.txt'),jabPayload);
console.log('JAB Code | '+jabPayload.length+' encoded characters | experimental encoder (no independent pixel decoder)');

// Zint implements Ultracode encoding. It is not supported by the ZXing decoder.
const script=readFileSync(file('examples/colormatch-ultra.js'),'utf8').trim();
const ultraPayload=packScript(script);
writeFileSync(file('assets/colormatch-ultra.txt'),ultraPayload);
for(const extension of ['svg','png']){
  execFileSync('zint',['--barcode=ULTRA','--scale=4','--input',file('assets/colormatch-ultra.txt').pathname,
    '--output',file('assets/colormatch-ultra.'+extension).pathname],{stdio:'pipe'});
}
const svg=readFileSync(file('assets/colormatch-ultra.svg'),'utf8');
if(!svg.includes('<svg'))throw Error('Ultracode generator failed');
console.log('Ultracode | '+ultraPayload.length+' encoded characters | generated by Zint (scanner unavailable)');
